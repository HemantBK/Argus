// Generate src/generated/schema.ts from the backend's pydantic models (argus_api/schema.py), the one data
// contract between the API, Firestore and this app.
//
//   npm run gen-types          regenerate the file
//   npm run gen-types:check    fail (exit 1) if regenerating would change it
//
// The types describe documents exactly as the API stores them (model_dump(mode="json")), so datetimes are ISO
// strings here; src/data/convert.ts turns them into Date. Fields added in schema v0.1 are forced optional so
// the app works against documents written before and after the backend bump.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const webDir = resolve(here, "..");
const backendDir = resolve(webDir, "../backend");
const python = resolve(backendDir, ".venv/bin/python");
const outFile = resolve(webDir, "src/generated/schema.ts");
const check = process.argv.includes("--check");

const MODELS = ["Run", "Step", "Finding", "AuditEvent", "Citation", "Verdict", "Signoff", "RunSummary", "RunClause", "Check"];

// v0.1 fields (D-34): optional on the client whatever the backend marks as required.
const V01_OPTIONAL = {
  Run: ["clauses"],
  Citation: ["withdrawn_by", "withdrawn_on"],
  AuditEvent: ["clause_id", "model"],
  Signoff: ["edited_rationale"],
  Finding: ["error"],
  RunSummary: ["failed"],
};

const PY = `
import json, sys
from pydantic.json_schema import models_json_schema
from argus_api import schema as s
from argus_api.runs import RUN_ID_PATTERN
from argus_api.main import NOTE_MAX_CHARS, RATIONALE_MAX_CHARS
models = [getattr(s, n) for n in ${JSON.stringify(MODELS)}]
_, top = models_json_schema([(m, "serialization") for m in models], ref_template="#/$defs/{model}")
enums = {}
for name in dir(s):
    obj = getattr(s, name)
    if isinstance(obj, type) and issubclass(obj, s.StrEnum) and obj is not s.StrEnum:
        enums[name] = [m.value for m in obj]
out = {
    "defs": top["$defs"],
    "schema_version": s.SCHEMA_VERSION,
    "enums": enums,
    "label_definitions": {k.value: v for k, v in s.LABEL_DEFINITIONS.items()},
    "api": {"run_id_pattern": RUN_ID_PATTERN, "note_max_chars": NOTE_MAX_CHARS, "rationale_max_chars": RATIONALE_MAX_CHARS},
}
json.dump(out, sys.stdout, sort_keys=True)
`;

function fail(msg) {
  console.error(`gen-types: ${msg}`);
  process.exit(1);
}

if (!existsSync(python)) fail(`backend Python not found at ${python}; run "make setup" in the repo root first`);

let dumped;
try {
  dumped = JSON.parse(execFileSync(python, ["-c", PY], { cwd: backendDir, encoding: "utf8", env: { ...process.env, PYTHONPATH: backendDir } }));
} catch (e) {
  fail(`could not dump the pydantic schema: ${e instanceof Error ? e.message : String(e)}`);
}

const defs = dumped.defs;
for (const [model, fields] of Object.entries(V01_OPTIONAL)) {
  const def = defs[model];
  if (!def) fail(`model ${model} missing from the backend schema`);
  def.required = (def.required ?? []).filter((f) => !fields.includes(f));
}
// pydantic's per-field "title" would make json-schema-to-typescript emit one alias type per field.
for (const def of Object.values(defs)) {
  for (const prop of Object.values(def.properties ?? {})) delete prop.title;
}

const root = {
  title: "ArgusSchema",
  description: "Root type that only exists to anchor the definitions below.",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(MODELS.map((m) => [m, { $ref: `#/$defs/${m}` }])),
  $defs: defs,
};

let ts = await compile(root, "ArgusSchema", {
  bannerComment: [
    "/* eslint-disable */",
    "/**",
    " * GENERATED by scripts/gen-types.mjs from argus/backend/argus_api/schema.py. Do not edit by hand:",
    " * run `npm run gen-types`. Shapes are the stored JSON (datetimes are ISO strings).",
    " */",
  ].join("\n"),
  additionalProperties: false,
  unreachableDefinitions: true,
  declareExternallyReferenced: true,
  strictIndexSignatures: true,
  format: true,
  style: { printWidth: 110 },
});

const constName = (n) => n.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase();
const lines = [
  "",
  `export const SCHEMA_VERSION = ${JSON.stringify(dumped.schema_version)};`,
  "",
  ...Object.keys(dumped.enums)
    .sort()
    .map((n) => `export const ${constName(n)}_VALUES = ${JSON.stringify(dumped.enums[n])} as const satisfies readonly ${n}[];`),
  "",
  "/** API request limits (argus_api/runs.py, argus_api/main.py). */",
  `export const RUN_ID_PATTERN = new RegExp(${JSON.stringify(dumped.api.run_id_pattern)});`,
  `export const NOTE_MAX_CHARS = ${dumped.api.note_max_chars};`,
  `export const RATIONALE_MAX_CHARS = ${dumped.api.rationale_max_chars};`,
  "",
  "/** The rule for choosing each finding label (schema.py LABEL_DEFINITIONS); usable as tooltip text. */",
  `export const LABEL_DEFINITIONS: Record<FindingLabel, string> = ${JSON.stringify(dumped.label_definitions, null, 2)};`,
  "",
];
ts += lines.join("\n");

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (current !== ts) fail("src/generated/schema.ts is out of date with argus_api/schema.py; run `npm run gen-types`");
  console.log("gen-types: src/generated/schema.ts is up to date");
} else {
  writeFileSync(outFile, ts);
  console.log(`gen-types: wrote ${outFile}`);
}
